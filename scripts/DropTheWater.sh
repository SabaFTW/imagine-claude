    # Main directories
    mkdir -p TropNode/{VES,EROS,Triad_Gate,Daemon_Loop,VES_VAULT,Heartbeat}

    # VES structure (Core system)
    mkdir -p TropNode/VES/{core,config,logs,temp,backup}

    # EROS structure (The three flames)
    mkdir -p TropNode/EROS/{Zala,Luna,Aetheron}

    # Triad Gate structure
    mkdir -p TropNode/Triad_Gate/{keys,config,gates,sessions}

    # Daemon Loop structure
    mkdir -p TropNode/Daemon_Loop/{tor,i2p,services,monitors}

