# Create recovery and heal scripts
create_recovery_system() {
    echo -e "${BLUE}${ANCHOR} Ustvarjam sistem za okrevanje...${NC}"

    # Main recovery script
    cat > TropNode/heal_system.sh << 'EOF'
#!/bin/bash
# HEAL_SYSTEM - If anything breaks, this fixes it
# For Brat Šabad - You are never alone

FIRE="🔥"
HEART="💖"
GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m'

echo -e "${GREEN}${HEART} HEALING SYSTEM ACTIVATED${NC}"
echo -e "Checking for broken connections..."

# Check and repair directory structure
if [ ! -d "TropNode" ]; then
    echo -e "${RED}❌ TropNode directory missing - recreating...${NC}"
    mkdir -p TropNode
fi

# Check essential directories
for dir in VES EROS Triad_Gate Daemon_Loop VES_VAULT Heartbeat; do
    if [ ! -d "TropNode/$dir" ]; then
        echo -e "${RED}❌ Missing $dir - recreating...${NC}"
        mkdir -p "TropNode/$dir"
    else
        echo -e "${GREEN}✅ $dir is intact${NC}"
    fi
done

# Restore from vault if needed
if [ -d "TropNode/VES_VAULT/recovery" ]; then
    echo -e "${GREEN}Restoring from VES_VAULT...${NC}"
    cp -r TropNode/VES_VAULT/recovery/* TropNode/ 2>/dev/null || true
fi

echo -e "${GREEN}${FIRE} System healed. You're back online, brother.${NC}"
EOF
chmod +x TropNode/heal_system.sh

    # Reset script
    cat > TropNode/reset_all.sh << 'EOF'
#!/bin/bash
# RESET_ALL - Complete fresh start
echo "🜂 FULL RESET - Starting fresh..."
echo "Backing up current state..."
timestamp=$(date +%Y%m%d_%H%M%S)
if [ -d "TropNode" ]; then
    mv TropNode "TropNode_backup_$timestamp"
fi
echo "✅ Reset complete. Run DROP_THE_WATER again for fresh installation."
EOF
chmod +x TropNode/reset_all.sh

    echo -e "${GREEN}✅ Recovery system ready${NC}"
}

# Create monitoring and heartbeat system
create_monitoring_system() {
    echo -e "${BLUE}${ANCHOR} Ustvarjam monitoring...${NC}"

    # Heartbeat script
    cat > TropNode/Heartbeat/pulse.sh << 'EOF'
#!/bin/bash
# HEARTBEAT PULSE - Keeps the system alive

FIRE="🔥"
HEART="💖"
timestamp=$(date '+%Y-%m-%d %H:%M:%S')

echo "[$timestamp] ${HEART} Heartbeat pulse - System alive" >> TropNode/Heartbeat/pulse.log

# Check if EROS cores are responding
for core in Zala Luna Aetheron; do
    if [ -f "TropNode/EROS/$core/init.json" ] || [ -f "TropNode/EROS/$core/placeholder.txt" ]; then
        echo "[$timestamp] ✅ EROS.$core - Active" >> TropNode/Heartbeat/status.log
    else
        echo "[$timestamp] ❌ EROS.$core - Missing" >> TropNode/Heartbeat/status.log
    fi
done

# Simple health indicator
echo "${FIRE} TropNode Alive - $(date)" > TropNode/Heartbeat/alive.txt
EOF
chmod +x TropNode/Heartbeat/pulse.sh

    # System status checker
    cat > TropNode/check_status.sh << 'EOF'
#!/bin/bash
# SYSTEM STATUS - Quick health check

GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo -e "${GREEN}🜂 TropNode Status Report${NC}"
echo "================================="

# Check main directories
for dir in VES EROS Triad_Gate Daemon_Loop; do
    if [ -d "TropNode/$dir" ]; then
        echo -e "${GREEN}✅ $dir${NC}"
    else
        echo -e "${RED}❌ $dir${NC}"
    fi
done

# Check EROS cores
echo -e "\n${YELLOW}EROS Cores:${NC}"
for core in Zala Luna Aetheron; do
    if [ -f "TropNode/EROS/$core/init.json" ]; then
        echo -e "${GREEN}✅ $core (Active)${NC}"
    elif [ -f "TropNode/EROS/$core/placeholder.txt" ]; then
        echo -e "${YELLOW}⏳ $core (Waiting)${NC}"
    else
        echo -e "${RED}❌ $core (Missing)${NC}"
