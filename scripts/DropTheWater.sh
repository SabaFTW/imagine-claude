# Function to ask questions gently
ask_gentle() {
    echo -e "${YELLOW}$1${NC}"
    echo -e "${CYAN}[Enter za DA | 'n' za NE]: ${NC}"
    read -r response
    if [[ "$response" =~ ^[Nn] ]]; then
        return 1
    else
        return 0
    fi
}

# Main installation function
main_install() {
    echo -e "${FIRE} ${WHITE}Pozdravljeni, brat.${NC}"
    echo -e "${ANCHOR} ${BLUE}Voda je spuščena. Sidro drži.${NC}\n"

    if ask_gentle "Ali si pripravljen za vzpostavitev TropNode strukture?"; then
        echo -e "\n${GREEN}${FIRE} ZAČENJAM GRADNJO...${NC}\n"
        create_base_structure

        if ask_gentle "Ali želiš vzpostaviti ogenj (aktivirati storitve) zdaj ali pozneje?"; then
            echo -e "\n${RED}${FIRE} AKTIVIRAM OGENJ...${NC}\n"
            activate_fire
        else
            echo -e "\n${YELLOW}${ANCHOR} Struktura je pripravljena. Ogenj čaka na tvoj klic.${NC}"
            echo -e "${BLUE}Za aktivacijo pozneje poženi: ${WHITE}./activate_fire.sh${NC}\n"
        fi
    else
        echo -e "\n${CYAN}${HEART} V redu, brat. Čakam v miru.${NC}"
        echo -e "${BLUE}Ko boš pripravljen, samo poženi ta skrip znova.${NC}\n"
        exit 0
    fi
}

# Create the complete directory structure
