export const portalByRoute = Object.fromEntries(
  portals.filter((portal) => portal.route).map((portal) => [portal.route, portal])
);

export const getCategory = (categoryId) =>
  portalCategories.find((category) => category.id === categoryId);

export function openPortal(portal) {
  if (!portal) return;

  if (portal.kind === 'react') {
    window.location.hash = portal.route;
    return;
  }

  window.open(portal.href, '_blank', 'noopener,noreferrer');
}
